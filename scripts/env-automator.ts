#!/usr/bin/env bun
/**
 * @file scripts/env-automator.ts
 * @description Intelligent Environment Automator for ΛΞVOS / B.E.E.P.
 * Automatically bootstraps, validates, tests connectivity, and populates `.env` files.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { randomBytes } from 'node:crypto';

const ROOT = resolve(import.meta.dir, '..');
const ENV_PATH = join(ROOT, '.env');
const EXAMPLE_PATH = join(ROOT, '.env.example');

const C = {
  cyan: '\x1b[0;36m',
  green: '\x1b[0;32m',
  yellow: '\x1b[1;33m',
  red: '\x1b[0;31m',
  dim: '\x1b[2m',
  bold: '\x1b[1m',
  nc: '\x1b[0m',
};

function generateSecret(length = 32): string {
  return randomBytes(length).toString('hex');
}

const APPLIANCE = process.env.BEEP_APPLIANCE === '1' || process.env.BEEP_OPERATOR === '1';

async function main() {
  if (!APPLIANCE) {
    console.log(`\n${C.cyan}╔══════════════════════════════════════════╗\n║  ΛΞVOS Intelligent Env Automator         ║\n╚══════════════════════════════════════════╝${C.nc}\n`);
  }

  if (!existsSync(EXAMPLE_PATH)) {
    console.error(`${C.red}✗ .env.example not found in workspace root.${C.nc}`);
    process.exit(1);
  }

  // 1. Read .env.example
  const exampleContent = readFileSync(EXAMPLE_PATH, 'utf-8');
  const exampleLines = exampleContent.split('\n');

  // 2. Read existing .env if present
  const existingEnv: Record<string, string> = {};
  if (existsSync(ENV_PATH)) {
    const envContent = readFileSync(ENV_PATH, 'utf-8');
    for (const line of envContent.split('\n')) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const eqIdx = trimmed.indexOf('=');
      if (eqIdx !== -1) {
        const key = trimmed.slice(0, eqIdx).trim();
        const val = trimmed.slice(eqIdx + 1).trim();
        existingEnv[key] = val;
      }
    }
    console.log(`${C.green}✓ Loaded existing .env file${C.nc}`);
  } else {
    console.log(`${C.yellow}⚠ No .env file found. Synthesizing from .env.example…${C.nc}`);
  }

  // 3. Intelligent Variable Synthesis & Population
  const updatedEnv: Record<string, string> = { ...existingEnv };

  for (const line of exampleLines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      if (!updatedEnv[key] || updatedEnv[key] === '') {
        // Appliance mode: local self-hosted Appwrite on port 80 (no cloud defaults).
        if (APPLIANCE && key.includes('APPWRITE')) {
          if (key.includes('ENDPOINT')) {
            updatedEnv[key] = 'http://localhost/v1';
            continue;
          }
          if (key.includes('PROJECT_ID')) {
            updatedEnv[key] = 'beep-local';
            continue;
          }
          if (key.includes('API_KEY') || key.endsWith('_KEY')) {
            updatedEnv[key] = `beep_sec_${generateSecret(16)}`;
            continue;
          }
        }

        if (!APPLIANCE && key.includes('APPWRITE')) {
          continue;
        }

        // Intelligently assign defaults based on key name
        if (key.includes('ENDPOINT')) {
          if (key.includes('APPWRITE')) updatedEnv[key] = 'https://tor.cloud.appwrite.io/v1';
          else updatedEnv[key] = 'http://localhost:11434';
        } else if (key.includes('URL')) {
          if (key.includes('OLLAMA')) updatedEnv[key] = 'http://localhost:11434';
          else if (key.includes('LITELLM')) updatedEnv[key] = 'http://localhost:4000';
          else if (key.includes('OPENROUTER')) updatedEnv[key] = 'https://openrouter.ai/api/v1';
          else updatedEnv[key] = 'http://localhost:3100';
        } else if (key.includes('MODEL')) {
          if (key.includes('ARCHITECT')) updatedEnv[key] = 'qwen2.5-coder';
          else if (key.includes('GEMMA')) updatedEnv[key] = 'gemma2';
          else if (key.includes('GRANITE')) updatedEnv[key] = 'granite3-dense';
          else updatedEnv[key] = 'qwen2.5-coder';
        } else if (key.includes('KEY') || key.includes('SECRET')) {
          updatedEnv[key] = `beep_sec_${generateSecret(16)}`;
        } else if (key.includes('PORT')) {
          if (key.includes('LITELLM')) updatedEnv[key] = '4000';
          else if (key.includes('MCP')) updatedEnv[key] = '3100';
          else updatedEnv[key] = '3000';
        } else {
          updatedEnv[key] = 'enabled';
        }
        console.log(`${C.dim}  + Auto-populated ${key} = ${updatedEnv[key].includes('sec_') ? '<REDACTED>' : updatedEnv[key]}${C.nc}`);
      }
    }
  }

  // 4. Write back to .env
  let newEnvFileContent = `# Generated by ΛΞVOS Intelligent Env Automator on ${new Date().toISOString()}\n`;
  for (const [k, v] of Object.entries(updatedEnv)) {
    newEnvFileContent += `${k}=${v}\n`;
  }
  writeFileSync(ENV_PATH, newEnvFileContent, 'utf-8');
  console.log(`${C.green}✓ .env file synchronized and secured successfully.${C.nc}`);

  // 5. Intelligent Service Probe
  console.log(`\n${C.bold}Probing local / cloud AI endpoints…${C.nc}`);
  const ollamaUrl = updatedEnv['OLLAMA_BASE_URL'] || 'http://localhost:11434';
  try {
    const res = await fetch(`${ollamaUrl}/api/tags`, { signal: AbortSignal.timeout(2000) });
    if (res.ok) {
      console.log(`${C.green}✓ Ollama reachable at ${ollamaUrl}${C.nc}`);
    } else {
      console.log(`${C.yellow}⚠ Ollama responded with status ${res.status}${C.nc}`);
    }
  } catch {
    console.log(`${C.dim}  · Ollama not currently active locally (non-blocking for UI dev)${C.nc}`);
  }

  if (APPLIANCE) {
    /* operator mode: no console output */
  } else {
    console.log(`\n${C.green}Environment automation complete. Dominion is ready to cast.${C.nc}\n`);
  }
}

main().catch(err => {
  console.error(`${C.red}✗ Env automation failed: ${err.message}${C.nc}`);
  process.exit(1);
});
